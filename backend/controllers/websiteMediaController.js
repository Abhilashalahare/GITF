// POST: Upload or replace a media placement
export const uploadWebsiteMedia = async (req, res) => {
  try {
    if (!req.file) {
      return res.status(400).json({
        success: false,
        message: 'Please select an image or video',
      });
    }

    const { name, key, section, altText = '' } = req.body;

    if (!name?.trim() || !key?.trim() || !section) {
      await deleteLocalMediaFile({
        filename: req.file.filename,
        mediaUrl: req.file.path,
      }).catch(() => {});

      return res.status(400).json({
        success: false,
        message: 'Name, key, and section are required',
      });
    }

    const normalizedKey = key.trim().toLowerCase();

    if (!validatePlacementKey(normalizedKey)) {
      await deleteLocalMediaFile({
        filename: req.file.filename,
        mediaUrl: req.file.path,
      }).catch(() => {});

      return res.status(400).json({
        success: false,
        message: 'Invalid placement key. Use format section/placement-name.',
      });
    }

    const mediaType = req.file.mimetype?.startsWith('video/')
      ? 'video'
      : 'image';

    const existingMedia = await WebsiteMedia.findOne({
      key: normalizedKey,
    });

    // Use the relative path produced by Multer's disk storage.
    // The filename is generated by the middleware.
    const relativePath = path.relative(
      uploadRoot,
      req.file.path
    ).split(path.sep).join('/');

    const mediaData = {
      name: name.trim(),
      key: normalizedKey,
      section,
      mediaUrl: `/uploads/website-media/${relativePath}`,
      filename: req.file.filename,
      mediaType,
      altText: typeof altText === 'string' ? altText.trim() : '',
      isActive: true,
    };

    let savedMedia;

    if (existingMedia) {
      const oldMedia = {
        filename: existingMedia.filename,
        mediaUrl: existingMedia.mediaUrl,
      };

      Object.assign(existingMedia, mediaData);
      savedMedia = await existingMedia.save();

      // Delete the old local file only after the database update succeeds.
      if (oldMedia.filename && oldMedia.filename !== req.file.filename) {
        try {
          await deleteLocalMediaFile(oldMedia);
        } catch (cleanupError) {
          console.error(
            'Old local website media cleanup failed:',
            cleanupError
          );
        }
      }
    } else {
      savedMedia = await WebsiteMedia.create(mediaData);
    }

    return res.status(201).json({
      success: true,
      message: existingMedia
        ? 'Website media replaced successfully'
        : 'Website media uploaded successfully',
      data: savedMedia,
    });
  } catch (error) {
    console.error('Upload website media error:', error);

    // Remove the newly uploaded local file if saving failed.
    if (req.file?.path) {
      try {
        const relativePath = path.relative(
          uploadRoot,
          req.file.path
        );

        const absolutePath = path.resolve(uploadRoot, relativePath);

        if (
          absolutePath.startsWith(uploadRoot + path.sep) &&
          path.basename(absolutePath) === req.file.filename
        ) {
          await fs.unlink(absolutePath).catch((cleanupError) => {
            if (cleanupError.code !== 'ENOENT') {
              throw cleanupError;
            }
          });
        }
      } catch (cleanupError) {
        console.error('Uploaded file cleanup failed:', cleanupError);
      }
    }

    if (error.code === 11000) {
      return res.status(409).json({
        success: false,
        message: 'This media placement already exists. Please try again.',
      });
    }

    return res.status(500).json({
      success: false,
      message: 'Failed to upload website media',
    });
  }
};

// PATCH: Activate or deactivate media
export const updateWebsiteMediaStatus = async (req, res) => {
  try {
    const { isActive } = req.body;

    if (typeof isActive !== 'boolean') {
      return res.status(400).json({
        success: false,
        message: 'isActive must be true or false',
      });
    }

    const media = await WebsiteMedia.findByIdAndUpdate(
      req.params.id,
      { isActive },
      { new: true, runValidators: true }
    );

    if (!media) {
      return res.status(404).json({
        success: false,
        message: 'Website media not found',
      });
    }

    return res.status(200).json({
      success: true,
      message: 'Website media status updated',
      data: media,
    });
  } catch (error) {
    console.error('Update website media status error:', error);

    return res.status(500).json({
      success: false,
      message: 'Failed to update website media status',
    });
  }
};

// DELETE: Delete local media and its MongoDB record
export const deleteWebsiteMedia = async (req, res) => {
  try {
    const media = await WebsiteMedia.findById(req.params.id);

    if (!media) {
      return res.status(404).json({
        success: false,
        message: 'Website media not found',
      });
    }

    // Remove the database record.
    await media.deleteOne();

    // Remove local files only; Cloudinary assets remain untouched.
    try {
      await deleteLocalMediaFile(media);
    } catch (cleanupError) {
      console.error(
        'Local website media cleanup failed:',
        cleanupError
      );

      return res.status(200).json({
        success: true,
        message:
          'Media record deleted, but its local file could not be removed.',
      });
    }

    return res.status(200).json({
      success: true,
      message: 'Website media deleted successfully',
    });
  } catch (error) {
    console.error('Delete website media error:', error);

    return res.status(500).json({
      success: false,
      message: 'Failed to delete website media',
    });
  }
};