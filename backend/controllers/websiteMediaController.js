import WebsiteMedia from '../models/WebsiteMedia.js';
import fs from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const uploadRoot = path.resolve(
  __dirname,
  '../uploads/website-media'
);

/**
 * Safely delete a locally stored website-media file.
 * Existing Cloudinary URLs are ignored.
 */
const deleteLocalMediaFile = async (media) => {
  if (!media?.filename || !media?.mediaUrl) return;

  const urlPrefix = '/uploads/website-media/';

  // Do not delete existing Cloudinary assets.
  if (!media.mediaUrl.startsWith(urlPrefix)) return;

  // Derive the relative path from the stored URL.
  const relativePath = decodeURIComponent(
    media.mediaUrl.slice(urlPrefix.length)
  );

  const filePath = path.resolve(uploadRoot, relativePath);

  // Prevent path traversal outside the upload directory.
  if (
    !filePath.startsWith(uploadRoot + path.sep) ||
    path.basename(filePath) !== media.filename
  ) {
    throw new Error('Invalid local media file path');
  }

  try {
    await fs.unlink(filePath);
  } catch (error) {
    if (error.code !== 'ENOENT') {
      throw error;
    }
  }
};

/**
 * Validate a placement key such as:
 * home/glimpse-1
 * about/intro-1
 */
const validatePlacementKey = (key) => {
  if (typeof key !== 'string') return false;

  const parts = key.split('/');

  return (
    parts.length === 2 &&
    parts.every((part) => /^[a-zA-Z0-9_-]+$/.test(part))
  );
};

// GET: Fetch active website media
export const getWebsiteMedia = async (req, res) => {
  try {
    const { section, key } = req.query;
    const filter = { isActive: true };

    if (section) filter.section = section;
    if (key) filter.key = key.trim().toLowerCase();

    const media = await WebsiteMedia.find(filter).sort({
      createdAt: -1,
    });

    return res.status(200).json({
      success: true,
      count: media.length,
      data: media,
    });
  } catch (error) {
    console.error('Get website media error:', error);

    return res.status(500).json({
      success: false,
      message: 'Failed to fetch website media',
    });
  }
};

