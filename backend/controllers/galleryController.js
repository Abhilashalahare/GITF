import GalleryItem from '../models/GalleryItem.js';
import cloudinary from '../config/cloudinary.js';

/*
 * Upload Gallery Item
 * POST /api/gallery/upload
 */
export const uploadGalleryItem = async (req, res) => {
  try {
    // Check if file was uploaded
    if (!req.file) {
      return res.status(400).json({
        success: false,
        message: 'Please select an image or video to upload.',
      });
    }

    const {
      title,
      school,
      year,
      category,
    } = req.body;

    // Validate required fields
    if (!title || !school || !year || !category) {
      /*
       * If Cloudinary already received the file but
       * required form data is missing, remove the file
       * so we don't leave an unused file in Cloudinary.
       */
      if (req.file.public_id) {
        try {
          await cloudinary.uploader.destroy(req.file.public_id, {
            resource_type: req.file.resource_type,
          });
        } catch (cloudinaryError) {
          console.error(
            'Cloudinary cleanup error:',
            cloudinaryError
          );
        }
      }

      return res.status(400).json({
        success: false,
        message: 'Title, school, year and category are required.',
      });
    }

    // Determine image/video
    const mediaType =
      req.file.resource_type === 'video'
        ? 'video'
        : 'image';

    /*
     * Create MongoDB record.
     *
     * req.file.public_id is generated by Cloudinary.
     * We DO NOT manually create this ID.
     */
    const newItem = await GalleryItem.create({
      title: title.trim(),
      school,
      year: year.trim(),
      category: category.trim(),
      mediaUrl: req.file.path,
      publicId: req.file.public_id || req.file.filename,
      mediaType,
    });

    return res.status(201).json({
      success: true,
      message: 'Gallery item uploaded successfully.',
      item: newItem,
    });
  } catch (error) {
    console.error('Gallery Upload Error:', error);

    /*
     * If Cloudinary upload succeeded but MongoDB failed,
     * remove the uploaded file from Cloudinary.
     */
    if (req.file?.public_id) {
      try {
        await cloudinary.uploader.destroy(
          req.file.public_id,
          {
            resource_type:
              req.file.resource_type || 'image',
          }
        );
      } catch (cloudinaryError) {
        console.error(
          'Cloudinary cleanup failed:',
          cloudinaryError
        );
      }
    }

    return res.status(500).json({
      success: false,
      message: 'Failed to upload gallery item.',
    });
  }
};


/*
 * Get Gallery Items
 * GET /api/gallery
 */
export const getGalleryItems = async (req, res) => {
  try {
    const items = await GalleryItem
      .find()
      .sort({ createdAt: -1 })
      .lean();

    return res.status(200).json({
      success: true,
      count: items.length,
      items,
    });
  } catch (error) {
    console.error('Gallery Fetch Error:', error);

    return res.status(500).json({
      success: false,
      message: 'Failed to fetch gallery items.',
    });
  }
};


/*
 * Delete Gallery Item
 * DELETE /api/gallery/:id
 */
export const deleteGalleryItem = async (req, res) => {
  try {
    const { id } = req.params;

    // Find item in MongoDB
    const item = await GalleryItem.findById(id);

    if (!item) {
      return res.status(404).json({
        success: false,
        message: 'Gallery item not found.',
      });
    }

    /*
     * Delete actual file from Cloudinary first.
     */
    if (item.publicId) {
      try {
        await cloudinary.uploader.destroy(
          item.publicId,
          {
            resource_type:
              item.mediaType === 'video'
                ? 'video'
                : 'image',
          }
        );
      } catch (cloudinaryError) {
        console.error(
          'Cloudinary Delete Error:',
          cloudinaryError
        );

        /*
         * Don't delete MongoDB record if Cloudinary
         * deletion failed.
         */
        return res.status(500).json({
          success: false,
          message:
            'Could not delete media from Cloudinary. Gallery item was not removed.',
        });
      }
    }

    // Delete MongoDB record
    await GalleryItem.findByIdAndDelete(id);

    return res.status(200).json({
      success: true,
      message: 'Gallery item deleted successfully.',
    });
  } catch (error) {
    console.error('Gallery Delete Error:', error);

    return res.status(500).json({
      success: false,
      message: 'Failed to delete gallery item.',
    });
  }
};